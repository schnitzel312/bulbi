"""Firewall backends: turn a :class:`NetworkPolicy` into kernel rules.

The gateway owns the box's network namespace and loads these rules there. The only
backend is nftables; others (e.g. iptables) would subclass :class:`FirewallBackend`.

Standard-library only: rendering happens inside the gateway image.
"""

from __future__ import annotations

import ipaddress
from abc import ABC, abstractmethod
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from enum import StrEnum
from types import MappingProxyType
from typing import ClassVar

from bulbi.gateway.policy import Action, NetworkPolicy, PortSegment, Reason
from bulbi.gateway.protected import PROTECTED_NETWORKS
from bulbi.gateway.rules import (
    AddressRule,
    HostRule,
    IPAddress,
    Protocol,
    Rule,
)

DOCKER_EMBEDDED_DNS = "127.0.0.11"
DNS_PORT = 53
RESOLVER_PORT = 5353
RESOLVER_HOST = "127.0.0.1"
RELATED_NOTE = "No conntrack helpers are assigned: 'related' only admits ICMP errors."
LOG_GROUP = 1
LOG_PREFIX = "bulbi"
LOG_FIELD_SEPARATOR = "|"
NO_RULE = "-"
MIN_PIN_SECONDS = 300


class PinKind(StrEnum):
    """What a DNS-learned address entry does: let traffic through or refuse it."""

    ALLOW = "pin"
    DENY = "block"


@dataclass(frozen=True)
class FirewallContext:
    """Runtime facts the ruleset needs besides the policy."""

    resolver_uid: int
    host_addresses: tuple[IPAddress, ...] = ()
    resolver_port: int = RESOLVER_PORT
    log_group: int = LOG_GROUP


@dataclass(frozen=True)
class AddressEntry:
    """A DNS-learned address with the protocol/port segments it applies to."""

    address: IPAddress
    segments: tuple[PortSegment, ...]
    ttl: int
    kind: PinKind = PinKind.ALLOW


@dataclass(frozen=True)
class LogTag:
    """What the firewall attaches to each logged connection attempt."""

    action: Action
    reason: Reason
    rule_id: int | None = None

    def encode(self) -> str:
        rule = NO_RULE if self.rule_id is None else str(self.rule_id)
        return LOG_FIELD_SEPARATOR.join((LOG_PREFIX, self.action, self.reason, rule))

    @classmethod
    def decode(cls, prefix: str) -> LogTag | None:
        """Parse a log prefix; ``None`` for anything that is not ours or is malformed."""
        parts = prefix.strip("\0 \n").split(LOG_FIELD_SEPARATOR)
        if len(parts) != 4 or parts[0] != LOG_PREFIX:  # noqa: PLR2004 - four fields
            return None
        try:
            action, reason = Action(parts[1]), Reason(parts[2])
            rule_id = None if parts[3] == NO_RULE else int(parts[3])
        except ValueError:
            return None
        return cls(action, reason, rule_id)


class FirewallBackend(ABC):
    """Renders the static ruleset and the commands that add DNS-learned entries."""

    @abstractmethod
    def render(self, policy: NetworkPolicy, context: FirewallContext) -> str:
        """The complete ruleset for the gateway namespace."""

    @abstractmethod
    def render_entries(self, entries: Iterable[AddressEntry]) -> str:
        """A script adding DNS-learned addresses (with timeouts) to the live ruleset."""


@dataclass
class _Lines:
    lines: list[str] = field(default_factory=list)

    def add(self, line: str = "", indent: int = 0) -> None:
        self.lines.append(f"{'    ' * indent}{line}" if line else "")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


class NftablesBackend(FirewallBackend):
    """nftables ``inet`` table ``bulbi``, loaded atomically with ``nft -f``.

    Egress order mirrors :meth:`PolicyMatcher.decide_connection`: established traffic,
    loopback, address/host rules (most specific first, deny first on ties), DNS pins,
    DNS blocks, protected ranges, default. Ingress drops every new connection.
    """

    TABLE: ClassVar[str] = "inet bulbi"
    _SET_TYPES: ClassVar[Mapping[int, str]] = MappingProxyType({4: "ipv4_addr", 6: "ipv6_addr"})
    _DADDR: ClassVar[Mapping[int, str]] = MappingProxyType({4: "ip daddr", 6: "ip6 daddr"})

    def render(self, policy: NetworkPolicy, context: FirewallContext) -> str:
        out = _Lines()
        out.add("#!/usr/sbin/nft -f")
        out.add("# Generated by bulbi. Do not edit.")
        out.add(f"table {self.TABLE}")
        out.add(f"delete table {self.TABLE}")
        out.add(f"table {self.TABLE} {{")
        for kind in PinKind:
            for version in (4, 6):
                self._render_set(out, f"{kind}{version}", version)
        self._render_dns_redirect(out, context)
        self._render_refuse(out)
        self._render_egress(out, policy, context)
        self._render_ingress(out)
        out.add("}")
        return out.text()

    def render_entries(self, entries: Iterable[AddressEntry]) -> str:
        out = _Lines()
        for entry in entries:
            elements = [
                f"{entry.address} . {segment.protocol} . {segment.ports} "
                f"timeout {max(entry.ttl, MIN_PIN_SECONDS)}s"
                for segment in entry.segments
            ]
            if elements:
                set_name = f"{entry.kind}{entry.address.version}"
                out.add(f"add element {self.TABLE} {set_name} {{ {', '.join(elements)} }}")
        return out.text()

    # ---- sections ------------------------------------------------------------

    def _render_set(self, out: _Lines, name: str, version: int) -> None:
        out.add(f"set {name} {{", 1)
        out.add(f"type {self._SET_TYPES[version]} . inet_proto . inet_service", 2)
        out.add("flags interval, timeout", 2)
        out.add("}", 1)

    def _render_dns_redirect(self, out: _Lines, context: FirewallContext) -> None:
        out.add("", 0)
        out.add("# Every DNS packet from the box goes to Bulbi's resolver (R5).", 1)
        out.add("chain dns_redirect {", 1)
        out.add("type nat hook output priority -150; policy accept;", 2)
        out.add(f"meta skuid {context.resolver_uid} return", 2)
        for protocol in Protocol:
            out.add(f"{protocol} dport {DNS_PORT} redirect to :{context.resolver_port}", 2)
        out.add("}", 1)

    @staticmethod
    def _render_refuse(out: _Lines) -> None:
        out.add("", 0)
        out.add("# Refuse visibly: ECONNREFUSED instead of a hang.", 1)
        out.add("chain refuse {", 1)
        out.add("meta l4proto tcp reject with tcp reset", 2)
        out.add("reject with icmpx port-unreachable", 2)
        out.add("}", 1)

    def _render_egress(self, out: _Lines, policy: NetworkPolicy, context: FirewallContext) -> None:
        out.add("", 0)
        out.add("chain egress {", 1)
        out.add("type filter hook output priority 0; policy drop;", 2)
        # Keep it that way: assigning a conntrack helper (FTP, SIP, ...) would let 'related'
        # accept helper-expected flows that bypass the ACL below.
        out.add(f"# {RELATED_NOTE}", 2)
        out.add("ct state established,related accept", 2)
        out.add("# DNS redirected to the resolver (still routed via eth0 at this point).", 2)
        out.add(
            f"meta l4proto {{ tcp, udp }} ip daddr {RESOLVER_HOST} "
            f"th dport {context.resolver_port} accept",
            2,
        )
        out.add("# The resolver may only reach Docker's DNS; nothing else is exempt.", 2)
        out.add(f"meta skuid {context.resolver_uid} ip daddr {DOCKER_EMBEDDED_DNS} accept", 2)
        out.add(f"meta skuid {context.resolver_uid} goto refuse", 2)
        refuse_docker_dns = self._verdict(Action.DENY, Reason.DENIED_PROTECTED, None, context)
        out.add(f'oif "lo" ip daddr {DOCKER_EMBEDDED_DNS} {refuse_docker_dns}', 2)
        out.add('oif "lo" accept', 2)
        out.add("# Address and host rules, most specific first; deny first on ties.", 2)
        for line in self._address_rule_lines(policy, context):
            out.add(line, 2)
        out.add("# Addresses learned from DNS answers for allowed / denied names.", 2)
        for kind, action, reason in (
            (PinKind.ALLOW, Action.ALLOW, Reason.ALLOWED_BY_DNS),
            (PinKind.DENY, Action.DENY, Reason.DENIED_BY_DNS),
        ):
            for version in (4, 6):
                verdict = self._verdict(action, reason, None, context)
                out.add(
                    f"meta l4proto {{ tcp, udp }} {self._DADDR[version]} . meta l4proto . "
                    f"th dport @{kind}{version} {verdict}",
                    2,
                )
        out.add("# Local and private destinations need an explicit address rule.", 2)
        for version in (4, 6):
            networks = ", ".join(str(n) for n in PROTECTED_NETWORKS if n.version == version)
            if version == 6:  # noqa: PLR2004 - IPv4-mapped forms of protected IPv4 ranges
                networks += ", ::ffff:0:0/96"
            verdict = self._verdict(Action.DENY, Reason.DENIED_PROTECTED, None, context)
            out.add(f"{self._DADDR[version]} {{ {networks} }} {verdict}", 2)
        default_reason = (
            Reason.ALLOWED_BY_DEFAULT
            if policy.default is Action.ALLOW
            else Reason.DENIED_BY_DEFAULT
        )
        out.add(self._verdict(policy.default, default_reason, None, context), 2)
        out.add("}", 1)

    @staticmethod
    def _render_ingress(out: _Lines) -> None:
        out.add("", 0)
        out.add("# Nothing may open a connection into the box (R3).", 1)
        out.add("chain ingress {", 1)
        out.add("type filter hook input priority 0; policy drop;", 2)
        # Keep it that way: assigning a conntrack helper (FTP, SIP, ...) would let 'related'
        # accept helper-expected flows that bypass the ACL below.
        out.add(f"# {RELATED_NOTE}", 2)
        out.add("ct state established,related accept", 2)
        out.add('iif "lo" accept', 2)
        out.add("}", 1)

    # ---- rules -----------------------------------------------------------------

    def _address_rule_lines(self, policy: NetworkPolicy, context: FirewallContext) -> list[str]:
        ranked = sorted(
            policy.rules_of((AddressRule, HostRule)),
            key=lambda item: (item[1].specificity(), item[0] is Action.DENY),
            reverse=True,
        )
        lines: list[str] = []
        for action, rule in ranked:
            reason = Reason.ALLOWED_BY_RULE if action is Action.ALLOW else Reason.DENIED_BY_RULE
            verdict = self._verdict(action, reason, policy.rule_id(rule), context)
            match = self._match(rule)
            for target in self._targets(rule, context):
                lines.append(f"{target} {match} {verdict}")
            if isinstance(rule, HostRule) and not context.host_addresses:
                lines.append(f"# '{rule}': no host address known, rule inactive")
        return lines

    def _targets(self, rule: Rule, context: FirewallContext) -> list[str]:
        if isinstance(rule, AddressRule):
            return [f"{self._DADDR[rule.network.version]} {rule.network}"]
        return [f"{self._DADDR[address.version]} {address}" for address in context.host_addresses]

    @staticmethod
    def _match(rule: Rule) -> str:
        protocols = sorted(rule.protocols)
        if len(protocols) == 1:
            proto = f"meta l4proto {protocols[0]}"
        else:
            proto = "meta l4proto { " + ", ".join(protocols) + " }"
        if rule.ports.is_all:
            return proto
        ports = ", ".join(str(port_range) for port_range in rule.ports.ranges)
        return f"{proto} th dport {{ {ports} }}"

    @staticmethod
    def _verdict(
        action: Action, reason: Reason, rule_id: int | None, context: FirewallContext
    ) -> str:
        tag = LogTag(action, reason, rule_id).encode()
        verdict = "accept" if action is Action.ALLOW else "goto refuse"
        return f'log group {context.log_group} prefix "{tag}" {verdict}'


def unique_addresses(addresses: Sequence[str]) -> tuple[IPAddress, ...]:
    """Parse and de-duplicate address strings, keeping order; invalid ones are skipped."""
    parsed: list[IPAddress] = []
    for text in addresses:
        try:
            address = ipaddress.ip_address(text)
        except ValueError:
            continue
        if address not in parsed:
            parsed.append(address)
    return tuple(parsed)
